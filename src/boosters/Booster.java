public class Boosters {
    
    String name;
    int    additionalBoost;
    int    mass;
    int    price;

    public Boosters(String name, int additionalBoost, int mass, int price) {
        this.name            = name;
        this.additionalBoost = additionalBoost;
        this.mass            = mass;
        this.price           = price;
    }

}